-- AUDIT TRAIL NOTE:
--   reviewed_by captures which admin approved/rejected a payment.
--   This field must never be cleared for paid/payment_rejected orders.
--   ON DELETE SET NULL applies only if the admin user account is deleted,
--   which should be a very rare event.
--   The reviewed_at timestamp always preserves the moment of decision.
--
-- PAID ORDERS MUST NOT BE DELETED:
--   ON DELETE RESTRICT on user_id and invitation_id prevents casual deletion
--   of financial records. Deletion of paid orders should require postgres-level
--   intervention and is expected to be an exceptional event.
--
